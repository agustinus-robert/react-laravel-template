import { Slot } from "@radix-ui/react-slot"
import { ChevronRight, MoreHorizontal } from "lucide-react"
import * as React from "react"

import { cn } from "@/lib/utils"

const IS_BOOTSTRAP =
  (import.meta.env.VITE_THEME || "tailwind") === "bootstrap"

function Breadcrumb({ ...props }: React.ComponentProps<"nav">) {
  return (
    <nav
      aria-label="breadcrumb"
      data-slot="breadcrumb"
      {...props}
    />
  )
}

function BreadcrumbList({ className, ...props }: React.ComponentProps<"ol">) {
  return (
    <ol
      data-slot="breadcrumb-list"
      className={cn(
        IS_BOOTSTRAP
          ? "breadcrumb d-flex flex-wrap align-items-center mb-0 small"
          : "text-muted-foreground flex flex-wrap items-center gap-1.5 text-sm break-words sm:gap-2.5",
        className
      )}
      {...props}
    />
  )
}

function BreadcrumbItem({ className, ...props }: React.ComponentProps<"li">) {
  return (
    <li
      data-slot="breadcrumb-item"
      className={cn(
        IS_BOOTSTRAP
          ? "breadcrumb-item d-inline-flex align-items-center"
          : "inline-flex items-center gap-1.5",
        className
      )}
      {...props}
    />
  )
}

function BreadcrumbLink({
  asChild,
  className,
  ...props
}: React.ComponentProps<"a"> & {
  asChild?: boolean
}) {
  const Comp = asChild ? Slot : "a"

  return (
    <Comp
      data-slot="breadcrumb-link"
      className={cn(
        IS_BOOTSTRAP
          ? "text-decoration-none"
          : "hover:text-foreground transition-colors",
        className
      )}
      {...props}
    />
  )
}

function BreadcrumbPage({ className, ...props }: React.ComponentProps<"span">) {
  return (
    <span
      data-slot="breadcrumb-page"
      role="link"
      aria-disabled="true"
      aria-current="page"
      className={cn(
        IS_BOOTSTRAP
          ? "text-body fw-normal"
          : "text-foreground font-normal",
        className
      )}
      {...props}
    />
  )
}

function BreadcrumbSeparator({
  children,
  className,
  ...props
}: React.ComponentProps<"li">) {
  return (
    <li
      data-slot="breadcrumb-separator"
      role="presentation"
      aria-hidden="true"
      className={cn(
        IS_BOOTSTRAP
          ? "d-inline-flex align-items-center text-secondary mx-2"
          : "[&>svg]:size-3.5",
        className
      )}
      {...props}
    >
      {children ?? (
        <ChevronRight
          className={IS_BOOTSTRAP ? "opacity-75" : ""}
          size={IS_BOOTSTRAP ? 14 : undefined}
        />
      )}
    </li>
  )
}

function BreadcrumbEllipsis({
  className,
  ...props
}: React.ComponentProps<"span">) {
  return (
    <span
      data-slot="breadcrumb-ellipsis"
      role="presentation"
      aria-hidden="true"
      className={cn(
        IS_BOOTSTRAP
          ? "d-inline-flex align-items-center justify-content-center"
          : "flex size-9 items-center justify-center",
        className
      )}
      {...props}
    >
      <MoreHorizontal
        className={IS_BOOTSTRAP ? "" : "size-4"}
        size={IS_BOOTSTRAP ? 16 : undefined}
      />
      <span className="sr-only">More</span>
    </span>
  )
}

export {
  Breadcrumb,
  BreadcrumbList,
  BreadcrumbItem,
  BreadcrumbLink,
  BreadcrumbPage,
  BreadcrumbSeparator,
  BreadcrumbEllipsis,
}